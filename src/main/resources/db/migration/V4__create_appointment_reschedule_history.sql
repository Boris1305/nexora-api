CREATE TABLE appointment_reschedule_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    appointment_id BIGINT NOT NULL,

    previous_start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    previous_end_at TIMESTAMP WITH TIME ZONE NOT NULL,

    new_start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    new_end_at TIMESTAMP WITH TIME ZONE NOT NULL,

    rescheduled_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reschedule_history_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointments(id),

    CONSTRAINT chk_reschedule_history_previous_dates
        CHECK (previous_end_at > previous_start_at),

    CONSTRAINT chk_reschedule_history_new_dates
        CHECK (new_end_at > new_start_at)
);

CREATE INDEX idx_reschedule_history_appointment
    ON appointment_reschedule_history(appointment_id);